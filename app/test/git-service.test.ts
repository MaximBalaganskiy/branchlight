import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rename } from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { GitService, parseStatus, validPath } = require('../electron/git-service.cjs');
const root = path.resolve('../.test-repos');
async function repository() {
  await mkdir(root, { recursive: true });
  const repo = await mkdtemp(path.join(root, 'git-test-'));
  const git = new GitService();
  await git.run(repo, ['init', '-b', 'main']);
  await git.run(repo, ['config', 'user.name', 'Branchlight Test']);
  await git.run(repo, ['config', 'user.email', 'test@example.invalid']);
  await git.run(repo, ['config', 'commit.gpgsign', 'false']);
  await git.run(repo, ['config', 'core.autocrlf', 'false']);
  return { repo, git };
}
test('staging, unstaging and committing preserve unstaged content, including an unborn branch', async () => {
  const { repo, git } = await repository();
  assert.equal((await git.snapshot(repo)).commits.length, 0);
  await writeFile(path.join(repo, 'file with spaces.txt'), 'first\n');
  await git.mutate(repo, 'stage', { paths: ['file with spaces.txt'] });
  assert.equal((await git.snapshot(repo)).files[0].staged, true);
  await writeFile(path.join(repo, 'file with spaces.txt'), 'edited before first commit\n');
  await git.mutate(repo, 'unstage', { paths: ['file with spaces.txt'] });
  assert.equal(await readFile(path.join(repo, 'file with spaces.txt'), 'utf8'), 'edited before first commit\n');
  assert.equal((await git.snapshot(repo)).files[0].index, '?');
  await writeFile(path.join(repo, 'file with spaces.txt'), 'first\n');
  await git.mutate(repo, 'stage', { paths: ['file with spaces.txt'] });
  await git.mutate(repo, 'commit', { message: 'Initial commit\n\nBody with context' });
  const initial = await git.snapshot(repo);
  assert.equal(initial.commits[0].subject, 'Initial commit');
  assert.equal(initial.branch, 'main');
  assert.equal(initial.files.length, 0);
  assert.equal((await git.detail(repo, initial.head)).files[0].path, 'file with spaces.txt');
  assert.match(await git.diff(repo, { path: 'file with spaces.txt', hash: initial.head }), /\+first/);
  await writeFile(path.join(repo, 'file with spaces.txt'), 'staged\n');
  await git.mutate(repo, 'stage', { paths: ['file with spaces.txt'] });
  await writeFile(path.join(repo, 'file with spaces.txt'), 'unstaged\n');
  const mixed = await git.snapshot(repo);
  assert.equal(mixed.files[0].index + mixed.files[0].worktree, 'MM');
  await git.mutate(repo, 'commit', { message: 'Commit index only' });
  assert.equal(await readFile(path.join(repo, 'file with spaces.txt'), 'utf8'), 'unstaged\n');
  assert.equal((await git.run(repo, ['show', 'HEAD:file with spaces.txt'])).stdout, 'staged\n');
  await assert.rejects(git.mutate(repo, 'checkout', { name: 'main' }), /Commit or stash/);
});
test('merge topology, pagination, first-parent diff and branch switching', async () => {
  const { repo, git } = await repository();
  await writeFile(path.join(repo, 'base.txt'), 'base\n');
  await git.mutate(repo, 'stage', { paths: ['base.txt'] });
  await git.mutate(repo, 'commit', { message: 'Root' });
  await git.mutate(repo, 'branch', { name: 'feature/graph' });
  await writeFile(path.join(repo, 'feature.txt'), 'feature\n');
  await git.mutate(repo, 'stage', { paths: ['feature.txt'] });
  await git.mutate(repo, 'commit', { message: 'Feature' });
  await git.mutate(repo, 'checkout', { name: 'main' });
  await writeFile(path.join(repo, 'main.txt'), 'main\n');
  await git.mutate(repo, 'stage', { paths: ['main.txt'] });
  await git.mutate(repo, 'commit', { message: 'Main' });
  await git.run(repo, ['merge', '--no-ff', 'feature/graph', '-m', 'Merge feature']);
  await git.run(repo, ['tag', '-a', 'v1', '-m', 'Annotated release']);
  const state = await git.snapshot(repo, 2);
  assert.equal(state.branches.find((b: any) => b.kind === 'tag').hash, state.head);
  assert.equal(state.commits.length, 2);
  assert.equal(state.hasMore, true);
  assert.equal(state.commits[0].parents.length, 2);
  assert.deepEqual((await git.detail(repo, state.head)).files, [{ status: 'A', path: 'feature.txt' }]);
  assert.match(await git.diff(repo, { path: 'feature.txt', hash: state.head }), /\+feature/);
});
test('literal pathspecs do not accidentally stage other files; rename unstage works', async () => {
  const { repo, git } = await repository();
  await writeFile(path.join(repo, '[abc].txt'), 'literal\n');
  await writeFile(path.join(repo, 'a.txt'), 'other\n');
  await git.mutate(repo, 'stage', { paths: ['[abc].txt'] });
  let state = await git.snapshot(repo);
  assert.equal(state.files.find((f: any) => f.path === 'a.txt').staged, false);
  await git.mutate(repo, 'commit', { message: 'Literal file' });
  await rename(path.join(repo, '[abc].txt'), path.join(repo, 'renamed.txt'));
  await git.mutate(repo, 'stage', { paths: ['[abc].txt', 'renamed.txt'] });
  state = await git.snapshot(repo);
  const file = state.files.find((f: any) => f.index === 'R');
  assert.equal(file.originalPath, '[abc].txt');
  await git.mutate(repo, 'unstage', { paths: [file.path, file.originalPath] });
  assert.equal((await git.snapshot(repo)).files.some((f: any) => f.staged), false);
  await assert.rejects(git.mutate(repo, 'stage', { paths: ['../outside'] }), /Invalid/);
  await assert.rejects(git.mutate(repo, 'commit', { message: 'Nothing staged' }), /Stage changes/);
});
test('NUL status parsing preserves unusual filenames and detects conflicts', () => {
  const files = parseStatus('R  new name\0old name\0?? ünicode.txt\0UU conflict.txt\0');
  assert.equal(files[0].path, 'new name');
  assert.equal(files[0].originalPath, 'old name');
  assert.equal(files[1].path, 'ünicode.txt');
  assert.equal(files[2].conflict, true);
  assert.throws(() => validPath('C:\\outside'), /Invalid/);
});
test('fetch, fast-forward pull and push work with a local remote', async () => {
  const { repo, git } = await repository();
  const bare = await mkdtemp(path.join(root, 'remote-'));
  await git.run(bare, ['init', '--bare', '-b', 'main']);
  await git.run(repo, ['remote', 'add', 'origin', bare]);
  await writeFile(path.join(repo, 'readme.txt'), 'v1\n');
  await git.mutate(repo, 'stage', { paths: ['readme.txt'] });
  await git.mutate(repo, 'commit', { message: 'First remote commit' });
  await git.run(repo, ['push', '-u', 'origin', 'main']);
  const clone = await mkdtemp(path.join(root, 'clone-'));
  await git.run(clone, ['clone', '-c', 'core.autocrlf=false', bare, '.']);
  await writeFile(path.join(repo, 'readme.txt'), 'v2\n');
  await git.mutate(repo, 'stage', { paths: ['readme.txt'] });
  await git.mutate(repo, 'commit', { message: 'Update remote' });
  await git.mutate(repo, 'push');
  await git.mutate(clone, 'fetch');
  assert.match((await git.snapshot(clone)).branches.find((b: any) => b.name === 'main').tracking, /behind 1/);
  await git.mutate(clone, 'pull');
  assert.equal(await readFile(path.join(clone, 'readme.txt'), 'utf8'), 'v2\n');
});
